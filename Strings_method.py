#strings are Immutable 
a= "!Rameshwar!"

print(a.upper())
print(a.lower())
print(a.capitalize())
print(a.count("R"))
print(a.replace("R","s"))
print(a.rstrip("!"))
print(a.split(" "))
print(len(a))

print(a.endswith("!"))
print(a.find("is"))

print(a.isalnum())
print(a.isalpha())
print(a.islower())
print(a.isupper())

print(a.isprintable())
print(a.isspace())
print(a.istitle())

print(a.startwith("r"))
print(a.swapcase())
print(a.title())
